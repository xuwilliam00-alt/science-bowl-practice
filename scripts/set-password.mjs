import { pbkdf2Sync, randomBytes } from 'node:crypto'
import { writeFileSync } from 'node:fs'
const pw = process.argv[2]
if (!pw || pw.length < 8) { console.error('Usage: npm run set-password -- "a long passphrase (8+ characters)"'); process.exit(1) }
const salt = randomBytes(16), iter = 210000, hash = pbkdf2Sync(pw, salt, iter, 32, 'sha256')
writeFileSync(new URL('../src/gateHash.ts', import.meta.url), `// Generated by \`npm run set-password\`. Empty hash = no password screen.\nexport const GATE = { salt: '${salt.toString('base64')}', hash: '${hash.toString('base64')}', iter: ${iter} }\n`)
console.log('Password set. Rebuild and commit to apply it.')
